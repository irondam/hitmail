// Extrait le code département depuis un code postal FR
export function cpToDept(cp) {
  if (!cp && cp !== 0) return null;
  const s = String(cp).trim().replace(/\s/g, "").padStart(5, "0");
  if (!/^\d{5}$/.test(s)) return null;
  // Outre-mer 3 chiffres : 971xx → 971, etc.
  const domPrefix = s.slice(0, 3);
  if (["970","971","972","973","974","975","976","977"].includes(domPrefix)) return domPrefix;
  // Corse : CP 20xxx → 2A (< 20200) ou 2B (>= 20200)
  if (s.startsWith("20")) return s < "20200" ? "2A" : "2B";
  return s.slice(0, 2);
}

export function getContactFromCP(cp) {
  const dept = cpToDept(cp);
  if (!dept) return { dept: null, departement: null, dt: null };
  const info = DEPT_INFO[dept];
  if (!info) return { dept, departement: null, dt: null };
  return { dept, departement: info.departement, dt: info.dt };
}